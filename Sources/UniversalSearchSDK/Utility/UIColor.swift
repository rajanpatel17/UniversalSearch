@available(iOS 11.0, *)
public extension UIColor {
    /// Create a UIColor from a hex string, with optional override for alpha.
    /// - Parameters:
    ///   - hex: A hex string like "#RRGGBB" or "#RRGGBBAA".
    ///   - alpha: Optional alpha override (default is 1.0)
    /// - Returns: UIColor
    class func hex(_ hex: String, alpha: Float = 1.0) -> UIColor {
        var hexString = hex.trimmingCharacters(in: .whitespacesAndNewlines).uppercased()
        if hexString.hasPrefix("#") {
            hexString.remove(at: hexString.startIndex)
        }

        let scanner = Scanner(string: hexString)
        var hexNumber: UInt64 = 0

        guard scanner.scanHexInt64(&hexNumber) else {
            return .clear
        }

        let r, g, b: CGFloat
        var a: CGFloat = CGFloat(alpha)

        switch hexString.count {
        case 6:
            // Format: RRGGBB
            r = CGFloat((hexNumber & 0xFF0000) >> 16) / 255
            g = CGFloat((hexNumber & 0x00FF00) >> 8) / 255
            b = CGFloat(hexNumber & 0x0000FF) / 255
            // Use passed alpha
        case 8:
            // Format: RRGGBBAA
            r = CGFloat((hexNumber & 0xFF000000) >> 24) / 255
            g = CGFloat((hexNumber & 0x00FF0000) >> 16) / 255
            b = CGFloat((hexNumber & 0x0000FF00) >> 8) / 255
            a = CGFloat(hexNumber & 0x000000FF) / 255
            // Override with parameter if alpha != 1
            if alpha != 1.0 {
                a = CGFloat(alpha)
            }
        default:
            return .clear
        }

        return UIColor(red: r, green: g, blue: b, alpha: a)
    }
}
